function formatBlock(obj) {
  const lines = ["  skuWorkbench: {"];
  for (const [key, value] of Object.entries(obj)) {
    if (value.includes("\n")) {
      lines.push(`    ${key}:`);
      lines.push(`      ${JSON.stringify(value)},`);
    } else {
      lines.push(`    ${key}: ${JSON.stringify(value)},`);
    }
  }
  lines.push("  },");
  return lines.join("\n");
}

for (const locale of LOCALES) {
  const file = join(ROOT, "src/i18n/messages", `${locale}.ts`);
  let src = readFileSync(file, "utf8");
  const re = /  skuWorkbench: \{[\s\S]*?\n  \},/;
  if (!re.test(src)) {
    console.error(`skuWorkbench block not found in ${locale}.ts`);
    process.exit(1);
  }
  src = src.replace(re, formatBlock(blocks[locale]));
  writeFileSync(file, src);
  console.log(`Patched ${locale}.ts`);
}
